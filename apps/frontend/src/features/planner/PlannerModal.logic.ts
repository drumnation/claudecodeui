export const calculateEstimatedTime = (
  selectedAgents: any,
  featureComplexity = 'medium',
) => {
  // Base time estimates per agent in seconds
  const baseTimeEstimates = {
    ARCH: 30,
    DIFF: 45,
    DEPS: 25,
  };

  // Complexity multipliers
  const complexityMultipliers = {
    simple: 0.7,
    medium: 1.0,
    complex: 1.5,
  };

  const multiplier = complexityMultipliers[featureComplexity] || 1.0;

  const totalEstimatedSeconds =
    selectedAgents.reduce((total: any, agent: any) => {
      return total + (baseTimeEstimates[agent] || 30);
    }, 0) * multiplier;

  return {
    seconds: totalEstimatedSeconds,
    formatted: formatDuration(totalEstimatedSeconds * 1000),
  };
};

export const validateProjectForPlanning = (project: any) => {
  const errors = [];

  if (!project) {
    errors.push('No project selected');
    return {isValid: false, errors};
  }

  if (!project.fullPath) {
    errors.push('Project path is not available');
  }

  if (!project.name) {
    errors.push('Project name is not available');
  }

  return {
    isValid: errors.length === 0,
    errors,
  };
};

export const shouldShowAgent = (agentType: any, selectedAgents: any) => {
  return selectedAgents.includes(agentType);
};

export const getNextAgent = (currentAgent: any, selectedAgents: any) => {
  if (!currentAgent) {
    return selectedAgents[0] || null;
  }

  const currentIndex = selectedAgents.indexOf(currentAgent);
  if (currentIndex === -1 || currentIndex === selectedAgents.length - 1) {
    return null; // No next agent
  }

  return selectedAgents[currentIndex + 1];
};

export const getPreviousAgent = (currentAgent: any, selectedAgents: any) => {
  if (!currentAgent) {
    return null;
  }

  const currentIndex = selectedAgents.indexOf(currentAgent);
  if (currentIndex <= 0) {
    return null; // No previous agent
  }

  return selectedAgents[currentIndex - 1];
};
