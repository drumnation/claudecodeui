// Utility functions for planner logic

export const validatePlannerRequest = (description: any, agents: any) => {
  const errors = [];

  if (!description || description.trim().length === 0) {
    errors.push('Feature description is required');
  }

  if (description && description.length > 1000) {
    errors.push('Feature description must be less than 1000 characters');
  }

  if (!agents || agents.length === 0) {
    errors.push('At least one agent must be selected');
  }

  const validAgents = ['ARCH', 'DIFF', 'DEPS'];
  const invalidAgents = agents.filter(
    (agent: any) => !validAgents.includes(agent),
  );
  if (invalidAgents.length > 0) {
    errors.push(`Invalid agents selected: ${invalidAgents.join(', ')}`);
  }

  return {
    isValid: errors.length === 0,
    errors,
  };
};

export const formatAgentProgress = (
  currentAgent: any,
  completedAgents: any,
  totalAgents: any,
) => {
  const completedCount = completedAgents.length;
  const progressPercentage =
    totalAgents > 0 ? (completedCount / totalAgents) * 100 : 0;

  let statusText = 'Initializing...';

  if (currentAgent) {
    statusText = `Running ${currentAgent} agent...`;
  } else if (completedCount === totalAgents) {
    statusText = 'Generating final plan...';
  } else if (completedCount > 0) {
    statusText = `Completed ${completedCount} of ${totalAgents} agents`;
  }

  return {
    statusText,
    progressPercentage: Math.round(progressPercentage),
    completedCount,
    totalAgents,
    isComplete: completedCount === totalAgents && !currentAgent,
  };
};

export const formatAgentOutput = (agentType: any, output: any) => {
  if (!output || output.trim().length === 0) {
    return '';
  }

  // Remove any markdown code blocks for display
  const cleanOutput = output
    .replace(/```[a-zA-Z]*\n?/g, '')
    .replace(/```/g, '')
    .trim();

  return cleanOutput;
};

export const createPlannerWebSocketMessage = (data: any) => {
  return {
    type: 'planner-command',
    projectPath: data.projectPath,
    featureDescription: data.featureDescription,
    selectedAgents: data.selectedAgents,
    plannerMode: data.plannerMode,
    autoGenerateCode: data.autoGenerateCode,
    screenshots: data.screenshots,
    sessionId: data.sessionId,
  };
};

export const parsePlannerResponse = (response: any) => {
  try {
    if (typeof response === 'string') {
      return JSON.parse(response);
    }
    return response;
  } catch (error) {
    console.error('Failed to parse planner response:', error);
    return {
      error: 'Invalid response format',
    };
  }
};

export const generateSessionFromPlan = (plan: any, projectPath: any) => {
  if (!plan || !projectPath) {
    throw new Error('Plan and project path are required');
  }

  const command = `I have a feature plan generated by multi-agent AI analysis. Please help me implement this feature step by step.

## Feature Plan

${plan}

## Next Steps

Please analyze this plan and help me:
1. Prioritize the implementation tasks
2. Set up the initial code structure
3. Begin implementing the core functionality

Let's start with the highest priority task from this plan.`;

  return {
    command,
    projectPath,
    sessionType: 'feature-implementation',
  };
};

